"""Tool contracts.

A tool is code registered by platform developers — never generated by a model. Each tool declares its
schemas, permission requirements, risk, side effects, timeout, idempotency and audit behaviour. The
policy engine (governance.policy) uses these declarations; the model only *requests* invocations.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path
from typing import TYPE_CHECKING, Any, ClassVar

from pydantic import BaseModel, ConfigDict, Field

from ..core.ids import content_hash
from ..spec.models import RiskLevel

if TYPE_CHECKING:
    from ..core.config import Settings
    from ..memory.knowledge import KnowledgeService


class SideEffect(StrEnum):
    READ = "read"
    WRITE = "write"
    EXTERNAL = "external"


class AuditConfig(BaseModel):
    log_arguments: bool = True
    log_output: bool = False


class ToolDefinition(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    version: str = "1.0.0"
    description: str
    connector: str
    input_schema: dict[str, Any]
    output_schema: dict[str, Any] = Field(default_factory=lambda: {"type": "object"})
    permissions: list[str] = Field(default_factory=lambda: ["tools:invoke"])
    timeout_seconds: float = 10.0
    risk: RiskLevel = RiskLevel.LOW
    side_effects: SideEffect = SideEffect.READ
    idempotent: bool = True
    action_class: str | None = None
    network: bool = False
    requires_sandbox: bool = False
    max_output_chars: int = 60_000
    audit: AuditConfig = Field(default_factory=AuditConfig)
    source: str = "builtin"

    @property
    def ref(self) -> str:
        return f"{self.name}@{self.version}"

    @property
    def hash(self) -> str:
        return content_hash(self.model_dump(mode="json"))

    def model_facing(self) -> dict[str, Any]:
        """What the model sees: name, description, parameters. No permissions or internals."""
        return {"name": self.name, "description": self.description, "parameters": self.input_schema}


@dataclass
class ToolContext:
    """Execution-scoped capabilities handed to a tool by the runtime (never to the model)."""

    workspace_id: str
    execution_id: str
    agent_name: str
    settings: Settings
    idempotency_key: str
    allowed_hosts: list[str] = field(default_factory=list)
    allowed_collections: list[str] = field(default_factory=list)
    knowledge: KnowledgeService | None = None
    fault_injection: dict[str, Any] = field(default_factory=dict)

    @property
    def sample_root(self) -> Path:
        return self.settings.sample_data_dir


class Tool(ABC):
    """Base class for registered tools. Subclasses set ``Input`` and ``definition_overrides``."""

    Input: ClassVar[type[BaseModel]]
    name: ClassVar[str]
    description: ClassVar[str]
    connector: ClassVar[str] = "builtin"
    output_schema: ClassVar[dict[str, Any]] = {"type": "object"}
    risk: ClassVar[RiskLevel] = RiskLevel.LOW
    side_effects: ClassVar[SideEffect] = SideEffect.READ
    timeout_seconds: ClassVar[float] = 10.0
    idempotent: ClassVar[bool] = True
    action_class: ClassVar[str | None] = None
    network: ClassVar[bool] = False
    requires_sandbox: ClassVar[bool] = False
    permissions: ClassVar[list[str]] = ["tools:invoke"]
    audit: ClassVar[AuditConfig] = AuditConfig()
    version: ClassVar[str] = "1.0.0"
    max_output_chars: ClassVar[int] = 60_000

    @property
    def definition(self) -> ToolDefinition:
        schema = self.Input.model_json_schema()
        schema.pop("title", None)
        return ToolDefinition(
            name=self.name,
            version=self.version,
            description=self.description,
            connector=self.connector,
            input_schema=schema,
            output_schema=self.output_schema,
            permissions=list(self.permissions),
            timeout_seconds=self.timeout_seconds,
            risk=self.risk,
            side_effects=self.side_effects,
            idempotent=self.idempotent,
            action_class=self.action_class,
            network=self.network,
            requires_sandbox=self.requires_sandbox,
            max_output_chars=self.max_output_chars,
            audit=self.audit,
        )

    def network_destination(self, arguments: dict[str, Any], settings: Settings) -> str | None:
        """Host this call will contact; ``None`` when the call uses no network. Default: the ``url`` argument."""
        from urllib.parse import urlsplit

        return urlsplit(str(arguments.get("url", ""))).hostname or ""

    @abstractmethod
    def run(self, args: Any, ctx: ToolContext) -> dict[str, Any]:
        """Execute with validated arguments. Raise ToolError for expected failures."""


def safe_join(root: Path, *parts: str) -> Path:
    """Join path parts under root, refusing traversal and symlink escapes."""
    from ..core.errors import ToolError

    root_resolved = root.resolve()
    candidate = root_resolved.joinpath(*parts).resolve()
    if not candidate.is_relative_to(root_resolved):
        raise ToolError("Path escapes the permitted directory", details={"code": "path_traversal"})
    return candidate
